// The bands come from persona-config.json, which is also what severity.js
// colours the tile from — so the scale shown here is the scale in force,
// and the row highlighted is the row that produced the tile's own colour.
function scaleRows(field, personaDef, tl) {
  const thresholds = personaDef?.tiles?.find((x) => x.field === field)?.thresholds;
  if (!thresholds) return '';
  // Which band to mark is decided by matching the label the tile is already
  // showing, not by re-classifying a raw value. Some tiles put the band name
  // in their value and some in their status line, and a couple of fields are
  // string enums rather than numbers — matching the rendered label sidesteps
  // all of that, and makes it impossible for the highlight to disagree with
  // the colour of the tile that opened this sheet.
  const shown = [tl?.statusLabel, tl?.value].filter(Boolean).map(String);
  return `
    <div class="explain-label">${t('explain.scale')}</div>
    <div class="explain-scale-hint">${t('explain.scale_hint')}</div>
    <div class="explain-scale">
      ${thresholds.map(([lo, hi, tone, label]) => {
        const name = t('status.' + label);
        const numeric = typeof lo === 'number';
        const range = !numeric ? ''
          : hi >= 900 ? `${lo}+`
          : lo === hi ? `${lo}`
          : `${lo}–${hi}`;
        const mine = shown.includes(name);
        const todo = pick(ADVICE[field]?.[label]);
        return `
          <div class="explain-band${mine ? ' mine' : ''}">
            <div class="explain-band-head">
              <span class="explain-band-dot" style="background:${TONE_COLOR[tone]}"></span>
              <span class="explain-band-range">${range}</span>
              <span class="explain-band-label">${name}</span>
              ${mine ? `<span class="explain-band-you">${t('explain.reading')}</span>` : ''}
            </div>
            ${todo ? `<div class="explain-band-do">${todo}</div>` : ''}
          </div>`;
      }).join('')}
    </div>`;
}

export function renderExplainSheet(field, personaDef, tl) {
  const e = EXPLAIN[field];
  if (!e) return '';
  return `
    <div class="explain-overlay" id="explain-overlay">
      <div class="explain-card" role="dialog" aria-modal="true" aria-labelledby="explain-title">
        <div class="explain-head">
          <div>
            <div class="explain-eyebrow">${t('explain.title')}</div>
            <h2 class="explain-title" id="explain-title">${tl?.label || ''}</h2>
          </div>
          ${tl ? `<div class="explain-now" style="color:${tl.color}">
            <span class="explain-now-value">${tl.value}</span>
            <span class="explain-now-unit">${tl.unit || ''}</span>
          </div>` : ''}
        </div>

        <div class="explain-source src-${e.source}">${t('explain.src.' + e.source)}</div>

        <div class="explain-label">${t('explain.what')}</div>
        <p class="explain-body">${pick(e.what)}</p>

        <div class="explain-label">${t('explain.how')}</div>
        <p class="explain-body">${pick(e.how)}</p>

        ${scaleRows(field, personaDef, tl)}

        <button class="explain-ok" id="explain-ok">${t('explain.close')}</button>
      </div>
    </div>`;
}
