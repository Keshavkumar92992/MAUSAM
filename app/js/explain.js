// What the numbers on the tiles actually mean.
//
// A tile says "UV index 8 · High" or "Rainfall 48 h — 12 mm" and assumes the
// reader already knows what a UV index is, or that rainfall is measured as a
// depth rather than a volume. Most people do not, and a farmer reading 12 mm
// has no way to turn that into water on a field. Every tile now carries an
// ⓘ that opens this.
//
// Three things live here and nothing else:
//   what   — what the number is, in one sentence
//   how    — how it is arrived at, including the instrument where there is one
//   source — live, derived, or simulated
//
// The scale is deliberately NOT here. Every banded tile already declares its
// thresholds in data/persona-config.json, and severity.js colours the tile
// from those; the sheet reads the same array. Restating the bands in this
// file would create a second copy to keep in step, and the first time they
// drifted the app would be explaining a scale it does not use.
//
// `source` is not decoration. Nine of these fields have no free keyless feed
// and are simulated by mock.js — plausible, deterministic, and not
// measurements. An app carrying the IMD's name should say so on the same
// screen that shows the number, not only in a README.
